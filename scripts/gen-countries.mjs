for (const [z, c] of Object.entries(aliases)) zones[z] ??= c;

const header = "// Generated by scripts/gen-countries.mjs from the IANA tz database. Do not edit by hand.\n\n";
writeFileSync(
  new URL("../src/lib/countries.ts", import.meta.url),
  header +
    `/** Every ISO 3166 country, English names, sorted by name. */
export const COUNTRIES: { code: string; name: string }[] = ${JSON.stringify(countries)};

export const COUNTRY_NAMES = new Set(COUNTRIES.map((c) => c.name));
`,
);
// Separate file so the browser only downloads the zone map, not the full list.
writeFileSync(
  new URL("../src/lib/zone-country.ts", import.meta.url),
  header +
    `/** IANA time zone -> ISO country code, used to guess the visitor's country. */
export const ZONE_COUNTRY: Record<string, string> = ${JSON.stringify(zones)};
`,
);
console.log(`countries: ${countries.length}, zones: ${Object.keys(zones).length}`);
