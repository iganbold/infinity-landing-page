// Generates src/lib/countries.ts and src/lib/zone-country.ts from the IANA tz database tables
// (iso3166.tab, zone.tab). Re-run if those tables change:
//   node scripts/gen-countries.mjs [/path/to/zoneinfo]
import { readFileSync, writeFileSync } from "node:fs";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const rows = (f) =>
  readFileSync(`${dir}/${f}`, "utf8")
    .split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => l.split("\t"));

const names = new Intl.DisplayNames(["en"], { type: "region" });
const countries = rows("iso3166.tab")
  .map(([code, tabName]) => {
    const n = names.of(code);
    return { code, name: n && n !== code ? n : tabName };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const zones = {};
for (const [code, , zone] of rows("zone.tab")) zones[zone] = code;
